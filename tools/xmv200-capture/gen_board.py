#!/usr/bin/env python3
# SPDX-License-Identifier: MIT
"""gen_board.py MERGED_TRACE PAGE_BIN NAME > board_NAME.c

A board's start-up as libxmv200's board program (board_prog.c), from a
capture of its vendor stack (README.md) running until it encodes. The
program is everything both vendor processes (Sofia and isp) set up before
the first frame:

- sensor I2C writes (bus 0) and register writes through /dev/mem;
- device ioctls;
- MMZ blocks, reallocated by name and size, with the addresses later
  payloads hold of them relocated;
- the ISP's shared page, filled after it is mapped.

Left out are what libxmv200 does itself: the encoder (hevc.ko jobs and its
buffers), frames (venc.ko and VPSS get/release), isp.ko's frame waits, the
periodic AE/ISP parameter updates after capture starts, cache flushes and
the NN blocks."""
import struct
import sys

trace, page_bin, name = sys.argv[1:4]
DEV = {'isp': 0, 'vpss': 1, 'vb': 2, 'sys': 3, 'mmz': 4, 'venc': 5, 'hevc': 6}
SKIP = {('mmz', 0x402c4d05), ('mmz', 0x402c4d06), ('isp', 0x490a),
        ('isp', 0x4909), ('venc', 0xc0284902), ('venc', 0x40284903),
        ('venc', 0x40284905), ('venc', 0x40104904), ('vpss', 0x4080500e),
        ('vpss', 0x4080500f), ('hevc', 0x4803), ('hevc', 0x4804)}
OWN_MMZ = (b'venc', b'stream', b'IA_', b'firm_mem', b'mempool', b'dst_mem')
BASE = {'sysctl': 0x20000000, 'isp2.vi': 0x30000000, 'isp2.vpss': 0x34000000,
        'isp2.bpu': 0x32000000}

steps, blob, pend = [], bytearray(), None
started_capture = 0
for ln in open(trace):
    f = ln.split()
    if not f:
        continue
    if f[0] == 'IOCTL':
        dev, cmd = f[2], int(f[3], 16)
        if dev == 'hevc' and cmd not in (0x40044806,):
            break                       # the first encoder job: start-up is over
        if dev not in DEV or (dev, cmd) in SKIP:
            continue
        data = bytes.fromhex(f[5]) if len(f) > 5 and not f[5].startswith('<') else b''
        if dev == 'mmz' and cmd in (0xc02c4d01, 0xc02c4d04):
            if data.startswith(OWN_MMZ):
                continue
            steps.append(['MMZ', cmd, len(blob), len(data), 0])
            blob += data
            pend = steps[-1]
            continue
        if dev == 'isp' and cmd == 0x495e:
            started_capture += 1
        steps.append(['IOC', DEV[dev], cmd, len(blob), len(data)])
        blob += data
        if dev == 'isp' and cmd == 0x400c490c:
            steps.append(['PAGE'])
    elif f[0] == 'R' and f[1] == 'mmz' and pend is not None:
        d = bytes.fromhex(f[4])
        if d[:32] == bytes(blob[pend[2]:pend[2] + 32]):
            pend[4] = struct.unpack_from('<I', d, 0x24)[0]
            pend = None
    elif len(f) == 5 and f[1] == 'U' and f[2] in BASE:
        steps.append(['REG', BASE[f[2]] + int(f[3], 16), int(f[4], 16)])
    elif len(f) == 5 and f[2] == 'sensor':
        a = int(f[3], 16)
        steps.append(['I2C', a >> 16, a & 0xffff, int(f[4], 16)])

page = open(page_bin, 'rb').read()
o = ['/* SPDX-License-Identifier: MIT */',
     '/* The %s board start-up for libxmv200, generated by' % name,
     ' * tools/xmv200-capture/gen_board.py from a capture of its vendor stack.',
     ' * Do not edit. */',
     '#include "board_prog.h"', '',
     'static const struct xmv200_prog_step steps[] = {']
for s in steps:
    if s[0] == 'IOC':
        o.append('    {XMV200_PROG_IOC, %d, 0x%08x, %d, %d, 0},' % (s[1], s[2], s[3], s[4]))
    elif s[0] == 'MMZ':
        o.append('    {XMV200_PROG_MMZ, 0, 0x%08x, %d, %d, 0x%08x},' % (s[1], s[2], s[3], s[4]))
    elif s[0] == 'REG':
        o.append('    {XMV200_PROG_REG, 0, 0x%08x, 0x%08x, 0, 0},' % (s[1], s[2]))
    elif s[0] == 'I2C':
        o.append('    {XMV200_PROG_I2C, %d, 0x%04x, 0x%02x, 0, 0},' % (s[1], s[2], s[3]))
    else:
        o.append('    {XMV200_PROG_PAGE, 0, 0, 0, 0, 0},')
o.append('};\n')
for cname, data in (('blob', bytes(blob)), ('page', page)):
    o.append('static const uint8_t %s[%d] = {' % (cname, len(data)))
    for i in range(0, len(data), 12):
        o.append('    ' + ', '.join('0x%02x' % b for b in data[i:i + 12]) + ',')
    o.append('};\n')
o += ['const struct xmv200_prog xmv200_prog_%s = {' % name.replace('-', '_'),
      '    .steps = steps,',
      '    .n_steps = sizeof(steps) / sizeof(steps[0]),',
      '    .blob = blob,',
      '    .page = page,',
      '    .page_size = sizeof(page),',
      '};']
print('\n'.join(o))
