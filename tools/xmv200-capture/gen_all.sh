#!/bin/bash
# SPDX-License-Identifier: MIT
# gen_all.sh CAPTURES_DIR [FAMILY [LIBDIR]]: a tuning per captured sensor of
# a chip family (xm530v200, xm535), and the registry of all families'
#
# A family's tunings are sns_<sensor>_tuning.c (xm530v200) or
# sns_<sensor>_<family>_tuning.c; sensors_<family>.list keeps which chip ID
# each is for, and sns_registry.c is made from every family's list.
set -e
C=$1; F=${2:-xm530v200}
L=${3:-$(cd "$(dirname "$0")/../../libraries/libxmv200" && pwd)}
D=$(cd "$(dirname "$0")" && pwd)
suffix=; [ "$F" = xm530v200 ] || suffix=_$F
list="$L/sensors_$F.list"
: > "$list.new"
for d in "$C"/*/; do
    id=$(basename "$d")
    name=$(grep -a -o '[A-Z0-9]*! Chn:0' "$d/console.log" 2>/dev/null | head -1 | cut -d'!' -f1)
    [ -n "$name" ] && grep -q SNAPSHOT "$d/merged.trace" || { echo "skip $id" >&2; continue; }
    n=$(echo "$name" | tr 'A-Z' 'a-z')$suffix
    "$D/gen_tuning.py" "$d/merged.trace" "$d/page.bin" "$d/ldc.bin" "$n" > "$L/sns_${n}_tuning.c"
    echo "$id $name $n" >> "$list.new"
done
sort -k3 "$list.new" > "$list"; rm -f "$list.new"
{
    echo '/* SPDX-License-Identifier: MIT */'
    echo '/* The sensors libxmv200 has tunings for, per chip family, generated by'
    echo ' * tools/xmv200-capture/gen_all.sh. Do not edit. */'
    echo '#include "sns_tuning.h"'
    echo
    cat "$L"/sensors_*.list | while read id name n; do
        echo "extern const struct xmv200_sns_tuning xmv200_tuning_$n;"
    done
    echo
    echo 'const struct xmv200_sns xmv200_sensors[] = {'
    cat "$L"/sensors_*.list | while read id name n; do
        echo "    {0x$id, \"$name\", &xmv200_tuning_$n},"
    done
    echo '};'
    echo
    echo 'const int xmv200_n_sensors = sizeof(xmv200_sensors) / sizeof(xmv200_sensors[0]);'
} > "$L/sns_registry.c"
