#!/bin/bash
# SPDX-License-Identifier: MIT
# gen_all.sh CAPTURES_DIR [LIBDIR]: a tuning per captured sensor, and the registry
set -e
C=$1; L=${2:-$(cd "$(dirname "$0")/../../libraries/libxmv200" && pwd)}
D=$(cd "$(dirname "$0")" && pwd)
reg=$(mktemp)
for d in "$C"/*/; do
    id=$(basename "$d")
    name=$(grep -a -o '[A-Z0-9]*! Chn:0' "$d/console.log" 2>/dev/null | head -1 | cut -d'!' -f1)
    [ -n "$name" ] && grep -q SNAPSHOT "$d/merged.trace" || { echo "skip $id" >&2; continue; }
    n=$(echo "$name" | tr 'A-Z' 'a-z')
    "$D/gen_tuning.py" "$d/merged.trace" "$d/page.bin" "$d/ldc.bin" "$n" > "$L/sns_${n}_tuning.c"
    echo "$id $name $n" >> "$reg"
done
{
    echo '/* SPDX-License-Identifier: MIT */'
    echo '/* The sensors libxmv200 has tunings for, generated by'
    echo ' * tools/xmv200-capture/gen_all.sh. Do not edit. */'
    echo '#include "sns_tuning.h"'
    echo
    sort -k3 "$reg" | while read id name n; do
        echo "extern const struct xmv200_sns_tuning xmv200_tuning_$n;"
    done
    echo
    echo 'const struct xmv200_sns xmv200_sensors[] = {'
    sort -k3 "$reg" | while read id name n; do
        echo "    {0x$id, \"$name\", &xmv200_tuning_$n},"
    done
    echo '};'
    echo
    echo 'const int xmv200_n_sensors = sizeof(xmv200_sensors) / sizeof(xmv200_sensors[0]);'
} > "$L/sns_registry.c"
rm -f "$reg"
