#!/usr/bin/env python3
"""Writes the XM530 ISP library's chroma table from chromasweep.so's log.

The vendor libisp_XM530.so builds the hue LUT (65 entries, 0x300710e4) from
the six colour strengths of ISP_CHROMA_ATTR_S. Swept one colour at a time,
an entry's departure from 0x80 is the strength's departure a = |s - 0x80|
less a threshold, never below 0, with the strength's sign: a - k1 up to a
cut, a - k2 from it (k1 = k2 without a cut). This finds k1, cut and k2 for
each colour and entry the colour reaches, and stops if any reading doesn't
fit.

Usage: chroma530.py SWEEP_LOG > libraries/libisp_XM530/arch/xm530/xm530_chroma.c
"""

import sys


def fit(g):
    """(k1, cut, k2) with g[a] = max(0, a - k1) for a < cut, else
    max(0, a - k2), for a = 0..128"""
    def ok(k1, cut, k2):
        return all(g[a] == (max(0, a - k1) if a < cut else max(0, a - k2))
                   for a in range(129))
    # one segment: g[128] = 128 - k unless k >= 128
    k = 128 - g[128] if g[128] else next(
        (128 - a for a in range(128, -1, -1) if g[a]), 129)
    if ok(0, 0, k):
        return (k, 0, k)
    for cut in range(1, 129):
        k2 = 128 - g[128] if g[128] else 128
        k1 = cut - 1 - g[cut - 1] if g[cut - 1] else None
        for k1 in ([k1] if k1 is not None else range(0, 129)):
            if ok(k1, cut, k2):
                return (k1, cut, k2)
    return None


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    data = {}
    for line in open(sys.argv[1]):
        p = [int(x) for x in line.split()]
        data[(p[0], p[1])] = [v - 0x80 for v in p[2:]]
    rows = []
    for c in range(6):
        for e in range(65):
            for a in range(1, 128):
                if data[(c, 0x80 + a)][e] != -data[(c, 0x80 - a)][e]:
                    sys.exit('chroma530: colour %d entry %d is not '
                             'symmetric' % (c, e))
            g = [abs(data[(c, 0x80 + a)][e]) for a in range(128)]
            g.append(abs(data[(c, 0)][e]))
            if not any(g):
                continue
            m = fit(g)
            if m is None:
                sys.exit('chroma530: colour %d entry %d fits no rule' % (c, e))
            rows.append((c, e) + m)
    o = sys.stdout
    o.write('/* The hue LUT\'s response to each colour strength, generated by\n'
            ' * tools/xm-isp-trace/chroma530.py from a chromasweep.so log of '
            'the\n * vendor library. Regenerate rather than edit. */\n\n')
    o.write('#include "xm530_start.h"\n\n')
    o.write('/* colour (Mg R Ye G Cy B), entry, k1, cut, k2 */\n')
    o.write('const struct xm530_chroma xm530_chroma[] = {\n')
    for r in rows:
        o.write('    {%d, %d, %d, %d, %d},\n' % r)
    o.write('    {0xff, 0, 0, 0, 0},\n};\n')


if __name__ == '__main__':
    main()
