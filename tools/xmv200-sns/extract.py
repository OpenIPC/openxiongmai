"""extract.py ISP SENSOR > ../../libraries/libxmv200/sns_SENSOR_regs.c

Writes a sensor's mode tables, as the vendor's isp daemon holds them, as C
arrays for libxmv200's driver of it (sns_SENSOR.c). ISP is that daemon from
a camera's firmware: the tables are at fixed addresses in one build of it,
checked by its MD5. Each table is register/value pairs of 16 bits each, and
the length is the one the vendor's init loop writes.
"""
import hashlib
import struct
import sys

# the XM530V200's isp ("[libsns]:Nov 20 2024 21:07:23 e89d30f"), from the
# X6C-WEQ's V5.04.R02.20241125 firmware
BUILDS = {
    "7d3a3a1ffcc84eb6d7bf3c41b8b9c2c8": {
        "base": 0x8000,  # the text segment's address, at file offset 0
        "sensors": {
            "sc2336": [
                # name, address, pairs, what the vendor logs for it
                ("sc2336_dvp", 0x85F72, 158, "SC2336 (@202207_dvp)"),
                ("sc2336_720p_mipi", 0x861EA, 168, "SC2336_720P mipi 25fps"),
                ("sc2336_mipi_1lane", 0x8648A, 158, "SC2336_1080P (@202308_mipi_1lane)"),
                ("sc2336_mipi", 0x86702, 149, "SC2336_1080P (@202311_mipi)"),
                ("sc2336p_mipi_1lane", 0x86956, 151, "SC2336P_1080P (202404_mipi_1lane)"),
                ("sc2336p_mipi", 0x86BB2, 149, "SC2336P_1080P (mipi)"),
                ("sc2336p_dvp", 0x86E06, 160, "SC2336P_1080P (dvp)"),
                ("sc2337p_dvp", 0x87F5E, 158, "SC2337_1080p (@20241008_dvp)"),
                ("sc2337p_mipi_1lane", 0x881D6, 158, "SC2337_1080P (@20241008_mipi_1lane)"),
                ("sc2337p_mipi", 0x8844E, 150, "SC2337_1080P (@20241008_mipi)"),
            ],
        },
    },
}


def main():
    isp, sensor = sys.argv[1], sys.argv[2]
    data = open(isp, "rb").read()
    md5 = hashlib.md5(data).hexdigest()
    if md5 not in BUILDS or sensor not in BUILDS[md5]["sensors"]:
        sys.exit("%s: unknown build %s or sensor %s" % (isp, md5, sensor))
    build = BUILDS[md5]
    print("/* SPDX-License-Identifier: MIT */")
    print("/* %s's mode tables for libxmv200 (sns_%s.c), generated by" % (sensor.upper(), sensor))
    print(" * tools/xmv200-sns/extract.py from the vendor isp %s */" % md5)
    print('#include "sns.h"')
    for name, addr, n, what in build["sensors"][sensor]:
        off = addr - build["base"]
        print("\n/* %s */" % what)
        print("const struct xmv200_sns_reg %s[%d] = {" % (name, n))
        for i in range(n):
            reg, val = struct.unpack_from("<HH", data, off + i * 4)
            if val > 0xff:
                sys.exit("%s: %04x = %x is not a byte" % (name, reg, val))
            print("    {0x%04x, 0x%02x}," % (reg, val))
        print("};")


main()
