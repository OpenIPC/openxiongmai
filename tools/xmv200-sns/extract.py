"""extract.py ISP SENSOR > ../../libraries/libxmv200/sns_SENSOR_regs.c

Writes a sensor's mode tables, as the vendor's isp daemon holds them, as C
arrays for libxmv200's driver of it (sns_SENSOR.c). ISP is that daemon from
a camera's firmware: the tables are at fixed addresses in one build of it,
checked by its MD5. Each table is register/value pairs of 16 bits each.

BUILD/SENSOR.tab lists the sensor's tables in that build, one a line: the
array's name, the address, the number of pairs (the vendor's init loop's),
and what the vendor logs for it. A line "format u8u8" makes the tables
after it pairs of bytes (sensors with 8-bit register addresses); the
default is "format u16u16".
"""
import hashlib
import os
import struct
import sys

# md5: the build's directory here, and its text segment's address (at file
# offset 0)
BUILDS = {
    # the XM530V200's ("[libsns]:Nov 20 2024 21:07:23 e89d30f"), from the
    # X6C-WEQ's V5.04.R02.20241125 firmware
    "7d3a3a1ffcc84eb6d7bf3c41b8b9c2c8": ("xm530v200", 0x8000),
}


def main():
    isp, sensor = sys.argv[1], sys.argv[2]
    data = open(isp, "rb").read()
    md5 = hashlib.md5(data).hexdigest()
    if md5 not in BUILDS:
        sys.exit("%s: unknown build %s" % (isp, md5))
    build, base = BUILDS[md5]
    tab = os.path.join(os.path.dirname(os.path.abspath(__file__)), build,
                       sensor + ".tab")
    print("/* SPDX-License-Identifier: MIT */")
    print("/* %s's mode tables for libxmv200 (sns_%s.c), generated by" %
          (sensor.upper(), sensor))
    print(" * tools/xmv200-sns/extract.py from the vendor isp %s */" % md5)
    print('#include "sns.h"')
    fmt, size = "<HH", 4
    for line in open(tab):
        if not line.strip() or line.startswith("#"):
            continue
        if line.split()[0] == "format":
            fmt, size = {"u16u16": ("<HH", 4), "u8u8": ("<BB", 2)}[line.split()[1]]
            continue
        name, addr, n, what = line.split(None, 3)
        addr, n = int(addr, 0), int(n, 0)
        print("\n/* %s */" % what.strip())
        print("const struct xmv200_sns_reg %s[%d] = {" % (name, n))
        for i in range(n):
            reg, val = struct.unpack_from(fmt, data, addr - base + i * size)
            if val > 0xff:
                sys.exit("%s: %04x = %x is not a byte" % (name, reg, val))
            print("    {0x%04x, 0x%02x}," % (reg, val))
        print("};")


main()
