#!/usr/bin/env python3
# SPDX-License-Identifier: MIT
"""extract.py ISP SENSOR > ../../libraries/libxmv200/sns_SENSOR_regs.c

Writes a sensor's mode tables, as the vendor's isp daemon holds them, as C
arrays for libxmv200's driver of it (sns_SENSOR.c). ISP is that daemon from
a camera's firmware: the tables are at fixed addresses in one build of it,
checked by its MD5. Each table is register/value pairs of 16 bits each.

BUILD/SENSOR.tab lists the sensor's tables in that build, one a line: the
array's name, the address, the number of pairs (the vendor's init loop's),
and what the vendor logs for it.
- A line "format u8u8" makes the tables after it pairs of bytes (sensors
  with 8-bit register addresses); the default is "format u16u16".
- A line "+ REG VAL" after a table appends a pair the vendor's init writes
  right after it, for a mode that is the table and those writes together.
- A name ending in :u8 or :u32 is a plain array of that many bytes or words
  instead (gain tables).
Addresses are in the text or the data segment.
"""
import hashlib
import os
import struct
import sys

# md5: the build's directory here, and its segments (address, file offset,
# size)
BUILDS = {
    # the XM530V200's ("[libsns]:Nov 20 2024 21:07:23 e89d30f"), from the
    # X6C-WEQ's V5.04.R02.20241125 firmware
    "7d3a3a1ffcc84eb6d7bf3c41b8b9c2c8": (
        "xm530v200", [(0x8000, 0, 0x9666C), (0xA7000, 0x97000, 0x60C0)]),
    # the XM533's ("Aug 26 2025 13:20:22 b7cb00d"), X3-WQ-B V5.04.R02.20250828
    "8002f9bb4c854d0058bca563df2d328b": (
        "xm533", [(0x8000, 0, 0x536A0), (0x636A0, 0x536A0, 0x1648)]),
    # the XM535D1's ("Aug 12 2025 09:11:27 d2db8e4"), X6E-WEQ V5.07.X02.20250906
    "87d4d77fd8028fcae2722a540f3864a6": (
        "xm535", [(0x10000, 0, 0x7E74C), (0x9EF24, 0x7EF24, 0x6FD8)]),
    # the XM535W1's ("Apr  7 2024 14:08:05 28505"), X2W-WNG V5.00.R02.20240410
    "b874c4f0f9ec4d3b2714b02fa55196d2": (
        "xm535w1", [(0x10000, 0, 0x56320), (0x76F1C, 0x56F1C, 0x3BD8)]),
}


def offset(segs, addr):
    for va, off, size in segs:
        if va <= addr < va + size:
            return addr - va + off
    sys.exit("%x is in no segment" % addr)


def main():
    isp, sensor = sys.argv[1], sys.argv[2]
    data = open(isp, "rb").read()
    md5 = hashlib.md5(data).hexdigest()
    if md5 not in BUILDS:
        sys.exit("%s: unknown build %s" % (isp, md5))
    build, segs = BUILDS[md5]
    tab = os.path.join(os.path.dirname(os.path.abspath(__file__)), build,
                       sensor + ".tab")
    fmt, size = "<HH", 4
    items = []  # (name, what, pairs) or (name, what, kind, values)
    for line in open(tab):
        if not line.strip() or line.startswith("#"):
            continue
        if line.split()[0] == "format":
            fmt, size = {"u16u16": ("<HH", 4), "u8u8": ("<BB", 2)}[line.split()[1]]
            continue
        if line.startswith("+"):
            _, reg, val = line.split()
            items[-1][2].append((int(reg, 0), int(val, 0)))
            continue
        name, addr, n, what = line.split(None, 3)
        addr, n = int(addr, 0), int(n, 0)
        if name.endswith(":u8") or name.endswith(":u32"):
            name, kind = name.split(":")
            vals = struct.unpack_from("<%d%s" % (n, "B" if kind == "u8" else "I"),
                                      data, offset(segs, addr))
            items.append((name, what.strip(), kind, vals))
            continue
        pairs = [struct.unpack_from(fmt, data, offset(segs, addr) + i * size)
                 for i in range(n)]
        items.append((name, what.strip(), pairs))

    print("/* SPDX-License-Identifier: MIT */")
    print("/* %s's mode tables for libxmv200 (sns_%s.c), generated by" %
          (sensor.upper(), sensor))
    print(" * tools/xmv200-sns/extract.py from the vendor isp %s */" % md5)
    print('#include "sns.h"')
    for item in items:
        print("\n/* %s */" % item[1])
        if len(item) == 4:
            name, _, kind, vals = item
            per = 12 if kind == "u8" else 6
            print("const %s %s[%d] = {" %
                  ("uint8_t" if kind == "u8" else "uint32_t", name, len(vals)))
            for i in range(0, len(vals), per):
                print("    " + " ".join(("0x%02x," if kind == "u8" else "0x%x,") % v
                                        for v in vals[i:i + per]))
            print("};")
            continue
        name, _, pairs = item
        print("const struct xmv200_sns_reg %s[%d] = {" % (name, len(pairs)))
        for reg, val in pairs:
            if val > 0xff:
                sys.exit("%s: %04x = %x is not a byte" % (name, reg, val))
            print("    {0x%04x, 0x%02x}," % (reg, val))
        print("};")


main()
